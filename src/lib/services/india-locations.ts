export const INDIAN_STATES_LIST: string[] = Object.keys(INDIAN_STATES_DISTRICTS);

/**
 * Returns canonical list of districts for a given state name.
 * Handles loose spellings like "tamilnadu" -> "Tamil Nadu".
 */
export function getDistrictsForState(stateName?: string | null): string[] {
  if (!stateName) return [];
  const clean = stateName.trim().toLowerCase().replace(/[\s\-_]/g, '');

  for (const [state, districts] of Object.entries(INDIAN_STATES_DISTRICTS)) {
    const sClean = state.toLowerCase().replace(/[\s\-_]/g, '');
    if (sClean === clean || sClean.includes(clean) || clean.includes(sClean)) {
      return districts;
    }
  }

  return [];
}

/**
 * Matches a free-form or user state to its official canonical state name.
 */
export function matchCanonicalState(rawState?: string | null): string {
  if (!rawState) return '';
  const clean = rawState.trim().toLowerCase().replace(/[\s\-_]/g, '');

  if (clean === 'tamilnadu' || clean === 'tn' || clean.includes('tamil')) {
    return 'Tamil Nadu';
  }

  for (const state of INDIAN_STATES_LIST) {
    const sClean = state.toLowerCase().replace(/[\s\-_]/g, '');
    if (sClean === clean || sClean.includes(clean) || clean.includes(sClean)) {
      return state;
    }
  }

  return rawState.trim();
}
